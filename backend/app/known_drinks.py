"""Довідник відомих напоїв та їхнього характерного складу.

Потрібен, щоб оцінити схожість згенерованої композиції з наявними
рецептурами. Веб-пошук за переліком інгредієнтів цього не дає: пошуковик не
знає, що «ялівець + коріандр + дягель + ірис + цитрус» — це джин. Тому
впізнавання робимо локально за цим довідником, а веб-пошук лишається для
посилання-підтвердження (див. services/similarity.py).

Склад описано за публічно відомими ботанічними профілями напоїв (те, що
виробники самі зазначають на етикетках і в описах), а не за закритими
рецептурами. Пропорції не наводяться — лише набір характерної сировини.

Поля:
  core     — визначальна сировина; без неї це не той напій (перевіряється
             жорстко: має бути присутня ВСЯ).
  typical  — решта характерного складу; впливає на глибину збігу.
  bases    — сумісні типи основи: spirit | wine | nonalcoholic | any.
  gi       — напій із захищеним географічним зазначенням.
  min_match— скільки інгредієнтів мінімум мають збігтися, щоб узагалі
             говорити про схожість (для однокомпонентних напоїв — 1).

Назви сировини мають збігатися з назвами в базі (`seed.py`), інакше збіг
не спрацює.
"""

