def base_kind(base_name: str | None) -> str:
    """Тип основи для перевірки сумісності з рецептурою."""
    if not base_name:
        return ANY
    lowered = base_name.lower()
    if "вино" in lowered:
        return WINE
    if "спирт" in lowered or "дистилят" in lowered:
        return SPIRIT
    return NONALC
