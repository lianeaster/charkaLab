NON_KEY_INTENSITY = 0.3
_COMPOUND_KIND = {c["name"]: c["kind"] for c in COMPOUNDS}


def _key_rank_intensity(position: int) -> float:
    """Сила ключової сполуки на позиції `position` (з 1) у списку статті."""
    return round(1 / math.sqrt(position), 2)


def _graded_intensity(compound: str, level: Optional[int], keys: Tuple[str, ...]) -> float:
    """Інтенсивність сполуки спеції з урахуванням ключових сполук статті."""
    if not keys or _COMPOUND_KIND.get(compound) == "taste":
        return LEVEL_INTENSITY[level]
    if compound in keys:
        graded = _key_rank_intensity(keys.index(compound) + 1)
        return max(graded, LEVEL_INTENSITY[2]) if level == 2 else graded
    return NON_KEY_INTENSITY


def _spice_materials() -> List[dict]:
    """Розгорнути таблицю спецій у записи сировини."""
    out: List[dict] = []
    for name, spec in SPICES.items():
        part = spec.get("part", "whole")
        keys = SPICE_KEY_ODORANTS.get((name, part), ())
        compounds: Dict[str, Optional[int]] = dict(spec["compounds"])
        for key in keys:
            compounds.setdefault(key, None)  # ключова, якої таблиця не мала
        links = []
        for compound, level in compounds.items():
            inten = _graded_intensity(compound, level, keys)
            links.append(_m(compound, "dry", "na", inten, part=part))
            if spec.get("fresh"):
                links.append(
                    _m(compound, "fresh", "na", round(inten * FRESH_FACTOR, 3), part=part)
                )
        entry = {
            "name": name,
            "has_pit_variants": False,
            "aliases": list(spec.get("aliases", [])),
            "compounds": links,
        }
        if spec.get("max_dose") is not None:
            entry["max_dose"] = spec["max_dose"]
        out.append(entry)
    return out


