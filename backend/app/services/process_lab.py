"""Просунутий рівень технологічної карти: фракції, апаратні методи, купаж.

Дома все настоюється в одній банці ступінчасто (services/process.py). Тут
кожен клас сировини — ОКРЕМА фракція: свій розчинник, своє співвідношення,
свій режим. Потім фракції змішуються за таблицею купажу. Окремі фракції дають
те, чого не дасть спільна банка: кожен клас обробляється в оптимумі, а баланс
можна дотягнути вже після мацерації, доливаючи фракцію за смаком.

Для апаратних методів режими точні — їх задає апарат, і саме тут похибка
коштує аромату:

Ультразвук. 35–40 кГц, 40–45 Вт на літр рідини, імпульсами. 40 Вт/л — рівень,
з якого екстракція з деревини дубу помітно зростала, а імпульси давали
синергію (Delgado-González et al. 2017, Ultrasonics Sonochemistry 36;
2022, doi:10.3390/foods11040517); ботаніка в спирті — 22 хв імпульсами при
45 Вт/л (Hielscher, виробник). Оптимум є: у вині 40 хв ультразвуку дали
приріст спиртів і естерів, довше — спад; ультразвук гріє суміш і виганяє
найлегші леткі сполуки (критичний огляд ультразвуку у виноробстві, PMC10457577), тому
температура під контролем, ємність закрита.
Теплий ультразвук (45–50 °C) — лише для щільної сухої сировини: в оптимізаціях
ультразвукової екстракції з плодів оптимум лежав при 51–55 °C (малина —
PMC7599779, Rubia sylvatica); ніжне й свіжі плоди не гріємо. Будь-який
нагрів настою — не вище 60 °C (суміш закипає близько 80 °C, банка закрита).
Спирт — лише в закритій банці, зануреній у воду ванни, не в самому баку.

Вакуум + ультразвук — послідовно: вакуумом вивести повітря з тканини, тоді
ультразвук при звичайному тиску (під вакуумом кавітація слабша: бульбашки
схлопуються тим сильніше, чим вищий тиск довкола).

Вакуум. −0,075…−0,08 МПа (20–25 кПа абсолютного тиску), 30 хв, 3 цикли —
режим негативно-тискової кавітаційної екстракції з листя (NPCE, PMC6268964).
Глибше не можна: водно-спиртова суміш при ~5 кПа (−0,95 бар) кипить уже при
кімнатній температурі й виносить аромат.

Ферменти. Пектиназа 40–70 мл/100 кг при 15–25 °C від 1 год або 20–40 мл/100 кг
при 45–50 °C 30 хв (дані виробника). β-глюкозидази пригнічуються етанолом:
при 15 % лишається 56–80 % активності, вище 16 % — падає (PMC8950599), тож
ферменти — плодам ДО заливання спиртом.

Гаряча інфузія. 55–60 °C від кількох годин до ночі — практика вермутів
(Difford's Guide); 60 °C 2 год — барна практика для спирту до 60 %.

Парова інфузія (кошик). Більше монотерпенів, ніж при мацерації, ліналоолу —
в 1,7 раза менше (Hodel et al. 2019, doi:10.1080/03610470.2019.1629263);
найбільше впливає кількість сировини на заряд, найменше — міцність заряду
(Hodel et al. 2020, doi:10.1002/jib.607).

Співвідношення сировини й спирту: плоди 1:1 (вишня — Sokół-Łętowska 2018;
малина — Duplais 1866), зелений горіх 1000–1200 г/л (Ordine del Nocino
Modenese), трави й прянощі 1:5–1:10 (фармакопейні настойки), ваніль ≈100 г/л
(стандарт ванільного екстракту США, 21 CFR 169.175).
"""

