def _options(cls: str, home_days: Tuple[float, float], pit_with: bool) -> List[MethodOption]:
    regime = LAB_REGIMES[cls]
    opts: List[MethodOption] = []
    us_time, us_after = US_BY_GROUP[regime.group]
    vac_us = regime.group in VAC_US_GROUPS
    if vac_us and cls in WARM_US_CLASSES and not pit_with:
        opts.append(MethodOption(
            equipment="ultrasound+vacuum+sousvide", title="Вакуум + теплий ультразвук",
            steps=VAC_THEN_US + US_COMMON + [
                "Термостат 45–50 °C, сеанс 20–30 хв.",
                HEAT_LIMIT,
                "Після: остудити банку закритою, далі настояти 1–2 доби, пробуючи щодня.",
            ],
        ))
    if cls in WARM_US_CLASSES and not pit_with:
        # ультразвукова ванна з підігрівом = ультразвук + термостат
        opts.append(MethodOption(
            equipment="ultrasound+sousvide", title="Теплий ультразвук",
            steps=US_COMMON + [
                "Термостат 45–50 °C, сеанс 20–30 хв.",
                HEAT_LIMIT,
                "Після: остудити банку закритою, далі настояти 1–2 доби, пробуючи щодня.",
            ],
        ))
    if vac_us:
        opts.append(MethodOption(
            equipment="ultrasound+vacuum", title="Вакуум + ультразвук",
            steps=VAC_THEN_US + US_COMMON + [
                f"Сеанс: {us_time}.", US_COOL, f"Після: {us_after}.",
            ],
        ))
    opts.append(MethodOption(
        equipment="ultrasound", title="Ультразвукова мацерація",
        steps=US_COMMON + [f"Сеанс: {us_time}.", US_COOL, f"Після: {us_after}."],
    ))
    vac_time, vac_after = VAC_BY_GROUP[regime.group]
    opts.append(MethodOption(
        equipment="vacuum", title="Вакуумна мацерація",
        steps=VAC_COMMON + [f"Режим: {vac_time}.", f"Після: {vac_after}."],
    ))
    if cls in SOUSVIDE_CLASSES and not pit_with:
        hours = "1–2 год" if cls in ("dry_herbs", "dried_fruit") else "2–6 год"
        opts.append(MethodOption(
            equipment="sousvide", title="Гаряча інфузія",
            steps=[
                f"Герметично (вакуумний пакет без повітря чи закрита банка), "
                f"55–60 °C, {hours}.",
                HEAT_LIMIT,
                "Остудити ЗАКРИТИМ — інакше леткі ноти й пари спирту підуть при "
                "відкриванні.",
            ],
        ))
    if cls in SIPHON_CLASSES:
        opts.append(MethodOption(
            equipment="siphon", title="Швидка інфузія під тиском",
            steps=[
                "Сифон 0,5–1 л, 1–2 балончики N₂O, 2–5 хв, періодично струшуючи.",
                "Різко стравити газ (сифон вертикально) — бульбашки рвуть клітини; "
                "одразу процідити.",
            ],
        ))
    if cls in STILL_CLASSES:
        opts.append(MethodOption(
            equipment="still", title="Парова інфузія (кошик)",
            steps=[
                "Сировину тонким шаром у кошик над кубом; заряд — нейтральний спирт "
                "45–65 %; перегнати повільно, відкинути голови.",
                "Головний важіль — кількість сировини на заряд, міцність заряду "
                "впливає найменше. Терпенів виходить більше, ніж мацерацією, "
                "ліналоолу — в 1,7 раза менше.",
                "Результат — прозорий ароматний дистилят без кольору й гіркоти; "
                "у купаж іде як окрема фракція.",
            ],
        ))
    lo, hi = home_days
    opts.append(MethodOption(
        equipment="none", title="Мацерація без обладнання",
        steps=[f"18–22 °C, темне місце, {_fmt_range(lo, hi)}; струшувати щодня."],
    ))
    return opts


def _pretreatments(cls: str) -> List[MethodOption]:
    out: List[MethodOption] = []
    if cls in FREEZE_CLASSES:
        out.append(MethodOption(
            equipment="freezer", title="Кріообробка",
            steps=[
                "Заморозити −18 °C щонайменше на 24 год; заливати спиртом ще "
                "замороженими — кристали льоду вже порвали клітини.",
            ],
        ))
    if cls in ENZYME_CLASSES:
        out.append(MethodOption(
            equipment="enzymes", title="Ферментна обробка (до спирту)",
            steps=[
                "Подрібнені плоди + пектиназа 40–70 мл/100 кг при 15–25 °C, від 1 год "
                "(або 20–40 мл/100 кг при 45–50 °C, 30 хв).",
                "Лише ДО заливання спиртом: ферменти пригнічуються етанолом, "
                "β-глюкозидаза вже при 16 % втрачає активність.",
                "Брати препарати з низькою пектинметилестеразною (PME) активністю — "
                "вона вивільняє з пектину метанол.",
            ],
        ))
    return out


def _loudness(dose: float) -> str:
    """Ціль для фракції: наскільки гучно звучить відносно основи (доза основи = 1)."""
    if dose >= 0.8:
        return "майже на рівні основи"
    if dose >= 0.4:
        return "≈ половина сили основи"
    if dose >= 0.2:
        return "чітко, але другим планом"
    return "легкий акцент"


def build(items: List[ProcessItem], classes: Sequence[str], amounts: Sequence[float]) -> Optional[LabProcess]:
    """Просунутий рівень для складу. classes — класи з process.classify."""
    fractions: Dict[str, Tuple[List[str], float, bool]] = {}
    is_main: Dict[str, bool] = {}
    late: List[str] = []
    for it, cls, amount in zip(items, classes, amounts):
        if MACERATION_CLASSES[cls].stage != "macerate":
            if cls != "sweetener":
                late.append(it.name)
            continue
        names, dose, pit = fractions.get(cls, ([], 0.0, False))
        names.append(it.name)
        # гучність фракції — за найгучнішим інгредієнтом у ній
        fractions[cls] = (names, max(dose, amount), pit or it.pit == "with")
        is_main[cls] = is_main.get(cls, False) or it.role == "main"
    if not fractions:
        return None

    order = sorted(fractions, key=lambda c: -sum(MACERATION_CLASSES[c].days))
    out_fractions: List[ProcessFraction] = []
    blend: List[BlendPart] = []
    for n, cls in enumerate(order, start=1):
        names, dose, pit_with = fractions[cls]
        regime = LAB_REGIMES[cls]
        title = f"Фракція {n} · {MACERATION_CLASSES[cls].title}"
        out_fractions.append(ProcessFraction(
            key=cls, title=title, ingredients=names,
            ratio=regime.ratio, abv=regime.abv,
            pretreatments=_pretreatments(cls),
            options=_options(cls, MACERATION_CLASSES[cls].days, pit_with),
        ))
        if is_main[cls]:
            blend.append(BlendPart(fraction=title, target="основа купажу — від неї рахуємо"))
        else:
            step = "0,5 мл" if regime.group in ("dense", "bitter") else "2 мл"
            blend.append(BlendPart(
                fraction=title, target=_loudness(dose),
                start=f"додавати по {step} на 100 мл основи",
            ))

    steps = [
        "Кожну фракцію зняти, віджати й профільтрувати окремо; записати об'єм і "
        "міцність кожної.",
        "Пробний купаж: до 100 мл основної фракції додавати допоміжні малими "
        "порціями (див. таблицю), пробуючи після кожної. Записати, на якій "
        "кількості нота з'являється і на якій починає домінувати — робоча доза "
        "між ними, ближче до цілі з таблиці.",
        "Знайдені пропорції перерахувати на весь об'єм. Окремі фракції саме й дають "
        "змогу дотягнути баланс після мацерації, а не вгадувати його наперед.",
    ]
    if late:
        steps.append(f"На купажі додати: {', '.join(late)}.")
    steps.append(
        "Підсолоджувати й доводити до міцності вже після купажу — сиропом, поступово."
    )
    cautions = [
        "Ультразвук гріє: без контролю температури настій «вариться», а найлегші "
        "ноти виходять із рідини.",
    ]
    if any(pit for _n, _d, pit in fractions.values()):
        cautions.append(
            "З кісточкою: ультразвук і вакуум прискорюють вихід амигдаліну так само, "
            "як аромату — кісточки лише цілі, гарячу інфузію не застосовувати."
        )
    return LabProcess(
        fractions=out_fractions,
        blend=blend,
        steps=steps,
        cautions=cautions,
        basis=[
            "ультразвук: 40 Вт/л, імпульси (Delgado-González 2017); 22 хв при 45 Вт/л "
            "для ботаніки (Hielscher); у вині понад 40 хв — спад аромату",
            "вакуум −0,075…−0,08 МПа, 3 цикли по 30 хв (NPCE)",
            "ферменти: пектиназа за даними виробника; β-глюкозидази пригнічуються "
            "етанолом понад ~15 %",
            "парова інфузія: Hodel 2019, 2020",
            "співвідношення: плоди 1:1 (Sokół-Łętowska 2018, Duplais 1866), трави й "
            "прянощі 1:5–1:10 (фармакопеї), ваніль ≈100 г/л (21 CFR 169.175)",
        ],
    )
