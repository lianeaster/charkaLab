def canon_name(spice: str) -> str:
    return SPICE_CANON.get(spice, spice.lower())


def new_compound_defs() -> List[dict]:
    """Список визначень нових сполук для COMPOUNDS у seed."""
    return [
        {"name": name, "kind": d["kind"], "characteristics": dict(d["chars"])}
        for name, d in NEW_COMPOUNDS.items()
    ]


def new_volatility() -> Dict[str, str]:
    return {name: d["vol"] for name, d in NEW_COMPOUNDS.items()}


def _mc(compound, form, intensity, part="whole"):
    return {"compound": compound, "part": part, "form": form,
            "pit": "na", "intensity": intensity}


def build_spice_materials() -> List[dict]:
    """Матеріали-спеції з таблиці (канонічні імена, суха + за потреби свіжа форма)."""
    out: List[dict] = []
    for spice, comps in SPICE_TABLE.items():
        name = canon_name(spice)
        links = []
        for tcomp, val in comps.items():
            comp = COMPOUND_MAP.get(tcomp, tcomp)
            inten = INTENSITY.get(int(val), 0.6)
            links.append(_mc(comp, "dry", inten))
            if name in FRESH_SPICES:
                links.append(_mc(comp, "fresh", round(inten * 0.95, 3)))
        out.append({
            "name": name,
            "has_pit_variants": False,
            "aliases": ALIASES.get(name, []),
            "compounds": links,
        })
    return out


def managed_names() -> set:
    return {canon_name(s) for s in SPICE_TABLE}

